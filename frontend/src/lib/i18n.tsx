const DICT: Record<LangCode, Record<TranslationKey, string>> = {
  en: EN,
  kk: KK,
  ru: RU,
};

export function readLang(): LangCode {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (LANGUAGES.some((l) => l.code === stored)) return stored as LangCode;
  } catch {
    // storage blocked
  }
  return "en";
}

type I18nContextValue = {
  lang: LangCode;
  locale: string;
  setLang: (code: LangCode) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue>({
  lang: "en",
  locale: "en-GB",
  setLang: () => {},
  t: (key) => EN[key],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(readLang);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((code: LangCode) => {
    setLangState(code);
    document.documentElement.lang = code;
    try {
      localStorage.setItem(STORAGE_KEY, code);
    } catch {
      // ignore
    }
  }, []);

  const locale = LANGUAGES.find((l) => l.code === lang)?.locale ?? "en-GB";

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      let text = DICT[lang][key] ?? EN[key];
      if (vars) {
        for (const [k, v] of Object.entries(vars)) {
          text = text.replaceAll(`{${k}}`, String(v));
        }
      }
      return text;
    },
    [lang],
  );

  return <I18nContext.Provider value={{ lang, locale, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
